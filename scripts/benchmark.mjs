/**
 * FR-49: the §6 benchmark profiles, measured against their fixtures and reported.
 *
 * `PRD.md` §6 draws the line this script obeys: "A target is not a measurement… A maximum observed on one
 * device does not become a promise that a slower reader's machine will break." So every line is one of two
 * kinds, and the distinction is the point of the file:
 *
 *  - **bar** — a structural property that holds on any machine, so it fails the run when it does not: the
 *    canvas count stays bounded, live pixel budget does not grow with scroll depth, the render caps bind
 *    where they are supposed to and degrade resolution rather than painting a blank page.
 *  - **measure** — a timing, printed with the machine it came from: document open, cold page, frame gaps,
 *    longest main-thread task. Headless Chromium has no vsync to hit, so "60 FPS" is not a thing this can
 *    honestly assert. No timing here is ever compared against *another* machine's number — §6: "a maximum
 *    observed on one device does not become a promise that a slower reader's machine will break" — but each
 *    one is compared against **this environment's own accepted baseline**, and that comparison can fail the
 *    job. That is FR-49's "a regression is a failing job rather than a slower feeling", and the leg-by-leg
 *    rules, the tolerance and the reason a leg cannot compare live in `scripts/benchmark-baseline.mjs`.
 *
 * A bar that cannot fail is not a bar, and cannot be wrong is not much either. Three of these went through
 * a version that did not measure what it said: the zoom test at 400 % on a dpr-1 desktop left the canvas at
 * 3.45 MP against a 33.6 MP ceiling, so "the cap held" described a run where no cap engaged — it is now run
 * at dpr 2 and 500 %, where the ceiling that applies is the screen-relative one and it bites; counting
 * canvases that had left the DOM but kept their buffer measured nothing, because a removed element is not
 * in `document` to be queried; and comparing the live *pixel* budget between the first and last third of a
 * scroll failed on profile A for a reason that was not a leak, because its pages have three different page
 * boxes — the count of held canvases is the box-independent shape of the claim, and that is what is asserted
 * now.
 *
 * Profiles come from §6's table. A is text-heavy (`long-sample.pdf`, 1,000 pages) and B image-heavy
 * (`scan-sample.pdf`, twelve 8.4-megapixel scans); C is vector-heavy (`vector-sample.pdf`, four A1 sheets at
 * ~13,000 engine operators each), and D is any of them on the committed low-memory harness — a phone-class
 * context with a CPU deliberately slowed through CDP. Every fixture is generated by a committed script under
 * `scripts/`, so the bytes in the report can be reproduced and hashed.
 *
 * D is a harness and says so. §6 asks profile D for "the committed low-memory harness **and** a real
 * mobile-device validation", and the second half cannot be done from this file on this machine; it stays open
 * as tasks #141 and #156, and the run prints that instead of implying a phone was involved.
 *
 * It needs a browser, so it is its own command — `npm run bench`, a step in CI's `browser` job — and not
 * part of `npm run verify`. Its record goes to `benchmarks/latest.json`, which is tracked, and the numbers a
 * run has been accepted as a baseline for go to `benchmarks/baseline.json`, also tracked and rewritten only
 * by `npm run bench:update-baseline`.
 */
