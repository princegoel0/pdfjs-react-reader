/**
 * Non-white pixel fraction over the whole of one page's canvas.
 *
 * The page is named because "is it painted yet" has to be a question about *that* page. The first draft asked
 * it of the first canvas in the DOM, which after a jump to page 500 is page 1's buffer — still painted from
 * the scroll that got there — so `waitForInk` returned immediately and the cold-page number measured a no-op.
 */
const INK = (pageNumber) => {
  const source = document.querySelector(`.pjsr-page-canvas[aria-label="Page ${pageNumber}"]`);
  if (!source || !source.width) return 0;
  const scratch = document.createElement('canvas');
  scratch.width = 240;
  scratch.height = 240;
  const ctx = scratch.getContext('2d', { willReadFrequently: true });
  ctx.drawImage(source, 0, 0, 240, 240);
  const { data } = ctx.getImageData(0, 0, 240, 240);
  let marks = 0;
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] < 8) continue;
    if (Math.abs(255 - data[i]) + Math.abs(255 - data[i + 1]) + Math.abs(255 - data[i + 2]) > 60) marks += 1;
  }
  return marks / (240 * 240);
};

const bar = (label, ok, detail) => ({ kind: 'bar', ok, label, detail });
/**
 * A timing, with the samples behind it.
 *
 * `values` is the record's payload and the reason it is not simply a printed number: §6 allows a baseline to be
 * reported only with its distribution, and a measure repeated five times has a p50 and a p95, while a measure
 * taken once has neither and says so. `sufficientForP99` follows the same rule from the other side — a 99th
 * percentile computed from five samples is a number that lies with three digits of precision.
 */
const measure = (label, detail, values = []) => ({ kind: 'measure', label, detail, values });
const note = (label, detail) => ({ kind: 'note', label, detail });

const pct = (sorted, q) => (sorted.length ? sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))] : 0);
const MP = (pixels) => `${(pixels / 1e6).toFixed(1)} MP`;
/** `performance.now()` differences are fractional and `Date.now()` differences are not; both get printed. */
const ms = (value) => `${Number(value).toFixed(1)} ms`;

/** §6's report fields, computed from the samples a measure was taken with. */
function distribution(values) {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return null;
  return {
    samples: sorted.length,
    p50: Number(pct(sorted, 0.5).toFixed(1)),
    p95: Number(pct(sorted, 0.95).toFixed(1)),
    // A 99th percentile of five samples is the maximum wearing a label; §6 asks for it only where the sample
    // count is sufficient, so it is reported as null rather than as a number nobody should believe.
    p99: sorted.length >= 100 ? Number(pct(sorted, 0.99).toFixed(1)) : null,
    max: Number(sorted[sorted.length - 1].toFixed(1)),
  };
}

/** The document the run measured, identified by its bytes rather than by its file name. */
function fixtureIdentity(name) {
  const bytes = readFileSync(join(repo, 'playground', 'fixtures', name));
  return { name, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
}

/**
 * Where the number came from, in the words §6 requires: machine model, OS, browser, engine, date.
 *
 * The model string is read from `os.cpus()` because that is what survives a clone — `wmic` and `systeminfo` are
 * not portable and a record that needs them is a record only this machine can produce.
 */
function environment(browser, engine) {
  let revision = 'unknown';
  try {
    revision = execSync('git rev-parse HEAD', { cwd: repo, encoding: 'utf8' }).trim();
  } catch {
    // A checkout without git still deserves a record; the revision is simply not knowable.
  }
  return {
    machine: cpus()[0]?.model?.trim() ?? 'unknown CPU',
    arch: machine(),
    platform: process.platform,
    osRelease: release(),
    memoryGb: Number((totalmem() / 1024 ** 3).toFixed(1)),
    node: process.version,
    browser: `chromium ${browser.version()}`,
    engine,
    revision,
    ranAt: new Date().toISOString(),
  };
}

/** Arm the frame-gap recorder and the long-task observer before any work happens. */
async function arm(page) {
  await page.evaluate(() => {
    window.__longest = 0;
    window.__frames = [];
    // §6 profile C's attribution: the viewer marks its own paint spans (`pjsr:` names) and discards the
    // entries as soon as they are made, so a reader has to be watching — this is that watcher.
    window.__spans = [];
    new PerformanceObserver((list) => {
      for (const entry of list.getEntries()) {
        if (entry.name.startsWith('pjsr:')) window.__spans.push({ name: entry.name, ms: entry.duration });
      }
    }).observe({ type: 'measure', buffered: true });
    new PerformanceObserver((list) => {
      for (const entry of list.getEntries()) window.__longest = Math.max(window.__longest, entry.duration);
      // `longtask` is buffered, so a task during the first paint is still seen — which is the one worth knowing about.
    }).observe({ type: 'longtask', buffered: true });
    let last = performance.now();
    const tick = (now) => {
      window.__frames.push(now - last);
      last = now;
      if (window.__frames.length < 900) requestAnimationFrame(tick);
    };
    requestAnimationFrame((now) => {
      last = now;
      requestAnimationFrame(tick);
    });
  });
}

async function openDocument(page, baseUrl, fixture) {
  await page.route(/raw\.githubusercontent\.com|unpkg\.com/, (route) => route.abort());
  await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.app-header');
  await page.selectOption('.app-header select', '/pdfjs-dist/');
  await arm(page);
  const started = Date.now();
  await page.fill('.app-url input[type=url]', new URL(`/fixtures/${fixture}`, baseUrl).href);
  await page.press('.app-url input[type=url]', 'Enter');
  await page.waitForSelector('.pjsr-page-canvas');
  const ink = await waitForInk(page, 1);
  return { openMs: Date.now() - started, ink };
}

/**
 * Wait for one named page to have ink on it.
 *
 * The page is named because "is it painted yet" has to be a question about *that* page. The first draft asked
 * it of the first canvas in the DOM, which during a jump is a page other than the one being waited for — still
 * mounted, already painted — so the wait returned at once and the cold-page timing measured the jump rather
 * than the render.
 */
async function waitForInk(page, pageNumber, timeout = 30_000) {
  const deadline = Date.now() + timeout;
  for (;;) {
    const ink = await page.evaluate(INK, pageNumber);
    if (ink > 0) return ink;
    if (Date.now() > deadline) return ink;
    await page.waitForTimeout(100);
  }
}

